--CREATE OR REPLACE VIEW VW_EMPLOYEES AS 
CREATE MATERIALIZED VIEW MVW_EMPLOYEES AS 
SELECT A.EMPLOYEE_ID,
        A.FIRST_NAME || ' ' || A.LAST_NAME AS NOMBRE_COMPLETO,
        B.DEPARTMENT_NAME,
        C.JOB_TITLE,
        C.MIN_SALARY,
        C.MAX_SALARY,
        D.FIRST_NAME || ' ' || D.LAST_NAME AS NOMBRE_DEL_JEFE,
        E.FIRST_NAME || ' ' || E.LAST_NAME AS NOMBRE_DEL_JEFE_DEPARTAMENTO,
        F.CITY,
        F.STREET_ADDRESS,
        G.COUNTRY_NAME,
        H.REGION_NAME
FROM EMPLOYEES A
LEFT JOIN DEPARTMENTS B
ON (A.DEPARTMENT_ID = B.DEPARTMENT_ID)
INNER JOIN JOBS C
ON (A.JOB_ID = C.JOB_ID)
LEFT JOIN EMPLOYEES D
ON (A.MANAGER_ID = D.EMPLOYEE_ID)
LEFT JOIN EMPLOYEES E
ON (B.MANAGER_ID = E.EMPLOYEE_ID)
LEFT JOIN LOCATIONS F
ON (B.LOCATION_ID = F.LOCATION_ID)
LEFT JOIN COUNTRIES G
ON (F.COUNTRY_ID = G.COUNTRY_ID)
LEFT JOIN REGIONS H
ON (G.REGION_ID = H.REGION_ID) 
ORDER BY A.EMPLOYEE_ID;


